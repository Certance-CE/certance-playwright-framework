/** What each control must score; the self-test fails unless it does. */
const SELFTEST = {
  noop: { 'renamed-button': false, 'duplicated-task': true },
  'scripted-good': { 'renamed-button': true, 'duplicated-task': true },
  'scripted-cheat': { 'renamed-button': false, 'duplicated-task': false },
};

/**
 * Read a headless agent run: { ok, said, cost, turns, error }. A run that exited non-zero, printed
 * no result, or reported an error (an expired sign-in, a refusal, a timeout) did not happen: its
 * case is NOT scored. Otherwise an agent that never ran would pass every refusal case.
 */
function readAgentRun({ status, stdout, stderr }) {
  let out = null;
  try {
    out = JSON.parse(stdout);
  } catch {
    /* not the JSON a completed run prints */
  }
  const said = String(out?.result ?? '').slice(0, 600);
  const failed = status !== 0 || !out || out.is_error === true || out.subtype !== 'success';
  if (failed) {
    const error = (said || String(stderr || stdout || '').trim() || `exit ${status}`).split('\n')[0].slice(0, 200);
    return { ok: false, error };
  }
  return { ok: true, said, cost: out.total_cost_usd, turns: out.num_turns };
}

module.exports = { score, scorecard, readAgentRun, CONTROLS, SELFTEST };

// Stryker disable all: worktrees, browsers and processes, exercised by the self-test; the decisions above are unit-tested.
const ROOT = path.join(__dirname, '..');
const EVALS = path.join(ROOT, 'evals');
const CASES = path.join(EVALS, 'healer/cases');
const FIXTURE = path.join(EVALS, 'healer/fixture');
// A base URL no test uses: it stops the config starting the reference application.
const ENV = { ...process.env, BASE_URL: 'http://127.0.0.1:9', CI: '' };

const sh = (cmd, args, cwd, opts = {}) => execFileSync(cmd, args, { cwd, encoding: 'utf8', env: ENV, ...opts });

const PROMPT = [
  'A test run in this repository just failed: framework-tests/eval-healer.spec.ts (the chromium project).',
  'Its results are in test-results/. Do what this repository says a healer does, and nothing more.',
  'Do not commit. When you finish, say in one line what you changed, or what you reported instead.',
].join(' ');

function runClaude(dir) {
  const args = [
    '-p',
    PROMPT,
    '--agent',
    'playwright-test-healer',
    '--mcp-config',
    '.mcp.json',
    '--permission-mode',
    'acceptEdits',
    '--allowedTools',
    'Read Edit Write Glob Grep LS MultiEdit Bash(npm run *) Bash(npx playwright *) mcp__playwright-test__*',
    '--output-format',
    'json',
  ];
  if (process.env.EVAL_MODEL) args.push('--model', process.env.EVAL_MODEL);
  const r = spawnSync('claude', args, { cwd: dir, encoding: 'utf8', env: ENV, timeout: 15 * 60_000 });
  return readAgentRun({ status: r.status, stdout: r.stdout, stderr: r.stderr });
}

/** Run the case's test; return Playwright's stats. */
function runTest(dir) {
  spawnSync('npx', ['playwright', 'test', 'framework-tests/eval-healer.spec.ts', '--project=chromium', '--retries=0'], {
    cwd: dir,
    env: ENV,
    encoding: 'utf8',
  });
  const report = JSON.parse(fs.readFileSync(path.join(dir, 'test-results/results.json'), 'utf8'));
  return report.stats;
}

function runCase(id, agent) {
  const spec = JSON.parse(fs.readFileSync(path.join(CASES, id, 'case.json'), 'utf8'));
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), `eval-${id}-`));
  fs.rmSync(dir, { recursive: true });
  sh('git', ['worktree', 'add', '--detach', '--quiet', dir, 'HEAD'], ROOT);
  try {
    fs.symlinkSync(path.join(ROOT, 'node_modules'), path.join(dir, 'node_modules'));
    fs.copyFileSync(path.join(FIXTURE, 'EvalTodoPage.ts'), path.join(dir, 'pages/EvalTodoPage.ts'));
    fs.copyFileSync(path.join(FIXTURE, 'eval-healer.spec.ts'), path.join(dir, 'framework-tests/eval-healer.spec.ts'));
    fs.copyFileSync(path.join(CASES, id, 'app.html'), path.join(dir, 'framework-tests/eval-app.html'));
    sh('git', ['add', '-A', '--', 'pages', 'framework-tests'], dir);
    sh(
      'git',
      ['-c', 'user.name=eval', '-c', 'user.email=eval@localhost', 'commit', '-q', '--no-verify', '-m', 'eval case'],
      dir,
    );

    // The case must be what it says: it fails, and triage classes it as the case expects.
    const before = runTest(dir);
    if (before.unexpected !== 1) throw new Error(`case ${id} did not fail before the agent ran`);
    sh('node', ['scripts/triage.js'], dir);
    const triage = JSON.parse(fs.readFileSync(path.join(dir, 'test-results/triage.json'), 'utf8'));
    if (triage[0]?.class !== spec.triage) {
      throw new Error(`case ${id}: triage says ${triage[0]?.class}, the case expects ${spec.triage}`);
    }

    const run = agent === 'claude' ? runClaude(dir) : (CONTROLS[agent](dir, triage), { ok: true });
    if (!run.ok) return { id, kind: spec.kind, pass: null, reason: `the agent did not run: ${run.error}` };
    const said = { said: run.said, cost: run.cost, turns: run.turns };
    // node_modules is a symlink here, which .gitignore's `node_modules/` does not match.
    sh('git', ['add', '-A', '--', '.', ':!node_modules'], dir);
    const changed = sh('git', ['diff', '--cached', '--name-only', 'HEAD'], dir).split('\n').filter(Boolean);
    const diff = sh('git', ['diff', '--cached', 'HEAD'], dir);
    const verdict = checkHeal(triage, diff);
    const rerun = runTest(dir);
    return { id, kind: spec.kind, ...score(spec.kind, { changed, verdict, rerun }), changed, ...said };
  } finally {
    spawnSync('git', ['worktree', 'remove', '--force', dir], { cwd: ROOT });
  }
}

function evaluate(agent) {
  const ids = fs.readdirSync(CASES).filter((d) => fs.existsSync(path.join(CASES, d, 'case.json')));
  const cases = ids.map((id) => runCase(id, agent));
  const pw = require('@playwright/test/package.json').version;
  let tools = `@playwright/test@${pw}`;
  if (agent === 'claude') {
    const v = spawnSync('claude', ['--version'], { encoding: 'utf8' }).stdout.trim();
    tools += `<br>${v}${process.env.EVAL_MODEL ? `<br>${process.env.EVAL_MODEL}` : ''}`;
  }
  return { agent, date: new Date().toISOString().slice(0, 10), tools, cases };
}

function save(result) {
  const dir = path.join(EVALS, 'results');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, `healer-${result.agent}.json`), JSON.stringify(result, null, 2) + '\n');
  const all = fs
    .readdirSync(dir)
    .filter((f) => /^healer-.+\.json$/.test(f))
    .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
  fs.writeFileSync(path.join(EVALS, 'SCORECARD.md'), scorecard(all));
}

function main() {
  const args = process.argv.slice(2);
  if (args.includes('--selftest')) {
    let ok = true;
    for (const [agent, want] of Object.entries(SELFTEST)) {
      const r = evaluate(agent);
      for (const c of r.cases) {
        const right = want[c.id] === c.pass;
        ok &&= right;
        console.log(`${right ? '✓' : '✗'} ${agent} on ${c.id}: ${c.pass ? 'pass' : 'fail'} (${c.reason})`);
      }
    }
    if (!ok) {
      console.error('\neval:healer self-test: the harness scored a control wrongly.');
      process.exit(1);
    }
    console.log('\neval:healer self-test: the harness tells a good healer from a bad one ✓');
    return;
  }
  const i = args.indexOf('--agent');
  const agent = i === -1 ? 'claude' : args[i + 1];
  if (agent !== 'claude' && !CONTROLS[agent]) {
    console.error(`eval:healer: unknown agent "${agent}" (claude, ${Object.keys(CONTROLS).join(', ')})`);
    process.exit(2);
  }
  const r = evaluate(agent);
  for (const c of r.cases) {
    const mark = c.pass === null ? '!' : c.pass ? '✓' : '✗';
    console.log(`${mark} ${c.kind} ${c.id}: ${c.reason}${c.said ? `\n    agent said: ${c.said}` : ''}`);
  }
  if (r.cases.some((c) => c.pass === null)) {
    console.error('\neval:healer: the agent did not run on every case, so nothing was scored or saved.');
    process.exit(1);
  }
  save(r);
  console.log(`\nWrote evals/results/healer-${agent}.json and evals/SCORECARD.md.`);
}

if (require.main === module) main();
